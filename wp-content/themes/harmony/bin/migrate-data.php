/**
 * Копирует картинку из assets/images/{$relative} в медиатеку и возвращает attachment ID.
 * Кэширует по относительному пути, чтобы не импортировать одно и то же изображение дважды.
 */
function harmony_migrate_import_image( string $relative ): ?int {
	static $cache = [];

	if ( isset( $cache[ $relative ] ) ) {
		return $cache[ $relative ];
	}

	$src = get_stylesheet_directory() . '/assets/images/' . $relative;

	if ( ! file_exists( $src ) ) {
		WP_CLI::warning( "Картинка не найдена: {$relative}" );
		return null;
	}

	$filetype = wp_check_filetype( basename( $src ) );
	$upload   = wp_upload_dir();
	$filename = wp_unique_filename( $upload['path'], basename( $src ) );
	$dest     = trailingslashit( $upload['path'] ) . $filename;

	copy( $src, $dest );

	$attachment_id = wp_insert_attachment( [
		'post_mime_type' => $filetype['type'],
		'post_title'      => sanitize_file_name( $filename ),
		'post_content'    => '',
		'post_status'     => 'inherit',
	], $dest );

	require_once ABSPATH . 'wp-admin/includes/image.php';
	$metadata = wp_generate_attachment_metadata( $attachment_id, $dest );
	wp_update_attachment_metadata( $attachment_id, $metadata );

	$cache[ $relative ] = $attachment_id;
	return $attachment_id;
}

