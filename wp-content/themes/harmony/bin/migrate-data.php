	$post_id = wp_insert_post( [
		'post_type'    => 'post',
		'post_title'   => $n['title'],
		'post_excerpt' => $n['excerpt'],
		'post_content' => $n['content'] ?? '',
		'post_status'  => 'publish',
		'post_date'    => DateTime::createFromFormat( 'd.m.Y', $n['date'] )->format( 'Y-m-d H:i:s' ),
	], true );

	if ( is_wp_error( $post_id ) ) {
		WP_CLI::warning( "Не удалось создать новость «{$n['title']}»: " . $post_id->get_error_message() );
		continue;
	}

	if ( ! empty( $n['image'] ) ) {
		$attachment_id = harmony_migrate_import_image( $n['image'] );
		if ( $attachment_id ) {
			set_post_thumbnail( $post_id, $attachment_id );
		}
	}

	WP_CLI::log( "Новость создана: {$n['title']} (ID {$post_id})" );
}

